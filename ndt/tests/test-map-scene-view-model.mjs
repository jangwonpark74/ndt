import assert from 'node:assert/strict';
import {createMapSceneViewModel} from '../dist/map-scene-view-model.mjs';

let timer, cancelled = 0, calls = 0;
const options = {schedule:(fn,delay)=>{assert.equal(delay,20000); calls++; timer=fn; return calls;},cancel:()=>{cancelled++;}};
const vm = createMapSceneViewModel(options);
let state;
vm.subscribe(value=>{state=value;});
vm.start(); vm.start();
assert.equal(calls,1);
assert.equal(state.phase,'loading');
const position = {lng:-79,lat:43};
const street = {source:'openmaptiles',sourceLayer:'transportation',properties:{render_height:100}};
const building = {source:'openmaptiles',sourceLayer:'building',properties:{render_height:35}};
vm.select([{source:'network'},street,building],position);
assert.deepEqual(state.selection,{location:position,height:35});
vm.select([street],position);
assert.deepEqual(state.selection,{location:position,height:0});
vm.select([{source:'network'}],position);
assert.equal(state.selection,null);
timer();
assert.equal(state.phase,'error');
vm.loaded();
assert.equal(state.phase,'ready');
const timely = createMapSceneViewModel(options);
timely.start();
timely.loaded();
assert.equal(cancelled,1);
assert.equal(timely.getState().phase,'ready');
console.log('Map scene view-model passed.');
