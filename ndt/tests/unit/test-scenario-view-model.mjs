import assert from 'node:assert/strict';
import {createScenarioViewModel} from '../../dist/scenario-view-model.mjs';
const version={revision:1,template:{rat:'NR'},overrides:{},sourceFingerprint:'source-1',modelVersion:'uma-element-v1'};
const saved={id:'one',name:'Study one',revision:1,baselineRevision:null,appliedRevision:null,versions:[version]};
let calls=[],release;
const model={load:async project=>project==='slow' ? new Promise(done=>release=done) : [saved],save:async(project,body)=>{calls.push([project,body]);return {...saved,revision:2,versions:[version,{...version,revision:2}]};}};
const vm=createScenarioViewModel(model);
await vm.load('fast');vm.select('one');
assert.equal(vm.getState().selected.id,'one');
vm.edit();assert.equal(vm.getState().dirty,true);
await vm.save({name:'Study one',template:version.template,overrides:{}});
assert.equal(calls[0][1].expectedRevision,1);assert.equal(vm.getState().dirty,false);
const slow=vm.load('slow');await vm.load('fast');release([]);await slow;
assert.equal(vm.getState().projectId,'fast');assert.equal(vm.getState().items.length,1);
const conflict=createScenarioViewModel({load:async()=>[saved],save:async()=>{throw Error('Scenario changed elsewhere');}});
await conflict.load('fast');conflict.select('one');conflict.edit();
await assert.rejects(conflict.save({name:'Draft',template:version.template,overrides:{}}));
assert.equal(conflict.getState().dirty,true);assert.equal(conflict.getState().selected.revision,1);
assert.match(conflict.getState().error,/changed elsewhere/);
let acceptSave;
const duringSave=createScenarioViewModel({load:async()=>[saved],save:()=>new Promise(done=>acceptSave=done)});
await duringSave.load('fast');duringSave.select('one');duringSave.edit({name:'First draft',template:version.template,overrides:{}});
const pendingSave=duringSave.save(duringSave.getState().draft);
duringSave.edit({name:'Newer draft',template:{rat:'LTE'},overrides:{}});
acceptSave({...saved,revision:2,versions:[version,{...version,revision:2}]});await pendingSave;
assert.equal(duringSave.getState().dirty,true,'edits made during a save remain unsaved');
assert.equal(duringSave.getState().draft.name,'Newer draft');
console.log('Scenario context isolation, CAS requests and conflict draft preservation passed.');
