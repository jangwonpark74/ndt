import assert from 'node:assert/strict';
import {createReservationsModel} from '../../dist/reservations-model.mjs';
import {createReservationsViewModel} from '../../dist/reservations-view-model.mjs';

const reservation = (id,status,lon) => ({type:'Feature',geometry:{type:'Point',coordinates:[lon,40]},properties:{id,status,on_street:`Street ${id}`}});
const features = [reservation('1','Installed',-74),reservation('2','Proposed',-73),reservation('3','Approved',-72)];
let resolve, loads = 0;
const vm = createReservationsViewModel({load:() => { loads++; return new Promise(done => {resolve=done;}); }});
let state;
vm.subscribe(value => {state=value;});
vm.setVisible(true);
const one = vm.load(), two = vm.load();
assert.equal(loads,1);
vm.setVisible(false);
resolve(features);
await Promise.all([one,two]);
assert.equal(state.visible,false);
assert.equal(state.loading,false);
vm.setVisible(true);
let results = vm.results(point=>point[0] <= -73,{lng:-74,lat:40});
assert.equal(results.inView,1);
assert.equal(results.total,3);
assert.equal(results.count,2);
vm.setQuery('proposed');
results = vm.results(()=>false,{lng:-74,lat:40});
assert.deepEqual(results.features,[features[1]]);
vm.select(features[1]);
assert.equal(state.selected,features[1]);

let attempts = 0;
const retry = createReservationsViewModel({load:async () => {if (++attempts===1) throw Error('offline'); return features;}});
await assert.rejects(retry.load(),/offline/);
assert.equal(retry.getState().error,true);
assert.deepEqual(await retry.load(),features);
assert.equal(retry.getState().error,false);
const model = createReservationsModel('/assets',async () => ({ok:true,json:async () => ({type:'FeatureCollection',features})}));
assert.deepEqual(await model.load(),features);
const invalid = createReservationsModel('/assets',async () => ({ok:true,json:async () => ({type:'FeatureCollection',features:[reservation(4,'Approved',-74)]})}));
await assert.rejects(invalid.load(),/Invalid reservation/);
console.log('Reservation model and view-model passed.');
