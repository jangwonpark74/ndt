import assert from 'node:assert/strict';
import { createSearchViewModel } from '../../dist/search-view-model.mjs';

const pending = [];
const vm = createSearchViewModel((query, center, signal) => new Promise((resolve, reject) => pending.push({query, center, signal, resolve, reject})));
let state;
vm.subscribe(value => { state = value; });
vm.setQuery('first');
const first = vm.submit({lat:43, lng:-79});
assert.equal(state.loading, true);
vm.setQuery('second');
assert.equal(pending[0].signal.aborted, true);
const second = vm.submit({lat:40, lng:-74});
pending[0].resolve([{label:'stale', coordinates:[0,0]}]);
await first;
assert.equal(state.loading, true);
assert.equal(state.status, 'Searching…');
const result = {label:'New York', coordinates:[-74,40]};
pending[1].resolve([result]);
await second;
assert.deepEqual(state.results, [result]);
vm.select(result);
assert.equal(state.query, 'New York');
assert.equal(state.open, false);
vm.setQuery('missing');
const empty = vm.submit({lat:0,lng:0});
pending[2].resolve([]);
await empty;
assert.equal(state.status, 'No locations found.');
const failed = vm.submit({lat:0,lng:0});
pending[3].reject(new Error('offline'));
await failed;
assert.equal(state.status, 'Search unavailable. Please try again.');
const dismissed = vm.submit({lat:0,lng:0});
vm.dismiss();
pending[4].reject(new Error('aborted'));
await dismissed;
assert.equal(state.open, false);
assert.equal(state.loading, false);
console.log('Location search view-model passed.');
