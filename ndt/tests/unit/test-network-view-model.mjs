import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createNetworkModel} from '../../dist/network-model.mjs';
import {createNetworkViewModel} from '../../dist/network-view-model.mjs';
import {RADIO_DEFAULTS} from '../../dist/radio-model.mjs';

const telus = JSON.parse(fs.readFileSync(new URL('../../dist/telus-sites.geojson',import.meta.url),'utf8'));
const bell = JSON.parse(fs.readFileSync(new URL('../../dist/bell-outdoor-sites.geojson',import.meta.url),'utf8'));
const model = createNetworkModel('/assets',async url => ({ok:true,json:async () => url.includes('telus') ? telus : bell}));
const loaded = await model.load();
assert.equal(loaded.length,telus.features.length+bell.features.length);
const invalid = createNetworkModel('/assets',async url => ({ok:true,json:async () => url.includes('telus') ? {...telus,record_count:0} : bell}));
await assert.rejects(invalid.load(),/Invalid network site data/);
const offline = createNetworkModel('/assets',async () => ({ok:false}));
await assert.rejects(offline.load(),/Network data request failed/);

const indoor = telus.features.find(f=>f.properties.records.some(r=>r.site_type === 'I'));
const site = bell.features.find(f=>f.geometry.coordinates[0] === -79.387538 && f.geometry.coordinates[1] === 43.702354);
let resolve, calls = 0;
const vm = createNetworkViewModel({load:() => {calls++; return new Promise(done=>{resolve=done;});}});
let state;
vm.subscribe(value=>{state=value;});
vm.setOptions({telus:true,bell:true,fansVisible:true,focus:false,query:'',scenario:RADIO_DEFAULTS});
const first = vm.load(), second = vm.load();
assert.equal(calls,1);
assert.equal(state.loading,true);
resolve([indoor,site]);
await Promise.all([first,second]);
assert.equal(state.loading,false);
let result = vm.coverage();
assert.equal(result.fans.features.length,3);
assert.equal(result.markers.length,2);
assert.match(result.status,/3 bearing estimates/);
vm.select(site,190);
vm.setOptions({focus:true});
result = vm.coverage();
assert.equal(result.selectedFans.features.length,3);
assert.equal(state.sector,190);
vm.setOptions({scenario:{...RADIO_DEFAULTS,eirpDbm:100}});
result = vm.coverage();
assert.match(result.status,/Enter EIRP/);
assert.equal(result.fans.features.length,0);
assert.deepEqual(result.markers,[indoor,site],'inventory survives invalid fan assumptions');
vm.setOptions({query:'mount pleasant',scenario:RADIO_DEFAULTS});
const list = vm.list(()=>true,{lng:-79.39,lat:43.7},14);
assert.deepEqual(list.features,[site]);
assert.match(list.listStatus,/1 matching/);
vm.setOptions({telus:false,bell:false});
assert.equal(vm.list(()=>true,{lng:0,lat:0},10),null);
vm.select(null);
assert.equal(state.selected,null);
let attempts = 0;
const retry = createNetworkViewModel({load:async()=>{if (++attempts===1) throw Error('offline'); return [site];}});
await assert.rejects(retry.load(),/offline/);
assert.equal(retry.getState().error,true);
assert.deepEqual(await retry.load(),[site]);
assert.equal(retry.getState().error,false);
console.log('Network model and view-model passed.');
