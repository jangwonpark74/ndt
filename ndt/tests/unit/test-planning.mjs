import assert from 'node:assert/strict';
import fs from 'node:fs';
import {RADIO_TEMPLATES,elementAttenuation,predictProbe,validateTemplate,siteTopology,siteLabel} from '../../dist/planning-model.mjs';
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
near(elementAttenuation(0,0),0);
near(elementAttenuation(32.5,0),3);
near(elementAttenuation(0,32.5),3);
near(elementAttenuation(180,0),30);
near(elementAttenuation(0,-6,6),0);
near(elementAttenuation(360,0),0);
const template=RADIO_TEMPLATES.nr,front=predictProbe(template,500,0),back=predictProbe(template,500,180);
assert.equal(validateTemplate(template),'');
assert.ok(back.rxDbm<front.rxDbm-25);
near(predictProbe({...template,powerDbm:43},500,0).rxDbm,front.rxDbm+3);
near(predictProbe({...template,lossDb:5},500,0).rxDbm,front.rxDbm-3);
near(predictProbe({...template,azimuthDeg:90},500,90).rxDbm,front.rxDbm);
near(predictProbe({...template,bandwidthMHz:20},500,0).rxDbm,front.rxDbm);
for(const distance of [9,5001,NaN])assert.ok(predictProbe(template,distance,0).error);
assert.ok(predictProbe({...template,frequencyMHz:NaN},500,0).error);
assert.ok(predictProbe({...template,pattern:'isotropic'},500,0).error);
const omni={...template,pattern:'isotropic',gainDbi:0};
near(predictProbe(omni,500,0).rxDbm,predictProbe({...omni,tiltDeg:30},500,180).rxDbm);
const bell=JSON.parse(fs.readFileSync(new URL('../../dist/bell-outdoor-sites.geojson',import.meta.url))).features[0];
const telus=JSON.parse(fs.readFileSync(new URL('../../dist/telus-sites.geojson',import.meta.url))).features[0];
assert.equal(siteTopology(bell).reduce((n,g)=>n+g.count,0),bell.properties.record_count);
assert.ok(siteTopology(bell,'NR').length);
assert.equal(siteTopology(telus,'NR').length,0);
assert.ok(siteTopology(telus,'LTE').length);
assert.match(siteLabel(bell),/Bell W2539/);
assert.match(siteLabel(telus),/TELUS ON1775/);
console.log('Planning reference element, probe, validation and inventory grouping passed.');
